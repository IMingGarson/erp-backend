        try:
            with transaction.atomic():
                for parent_code, data in recipes.items():
                    # 1. 建立母件
                    parent_mat, _ = Material.objects.get_or_create(
                        code=parent_code,
                        defaults={
                            "name": data["name"],
                            "type": data["type"],
                            "unit": "KG",
                            "created_by": user,
                        },
                    )
                    materials_created += 1

                    # 2. 建立子件與 BOM
                    for child_code, child_name in data["items"]:
                        # 判斷是半成品還是原料
                        child_type = "SEMI" if child_code.startswith("P") else "RAW"

                        child_mat, _ = Material.objects.get_or_create(
                            code=child_code,
                            defaults={
                                "name": child_name,
                                "type": child_type,
                                "unit": "KG",
                                "created_by": user,
                            },
                        )
                        materials_created += 1

                        # 模擬配方用量：實務上基底油水較重，香料較輕。這裡做個簡單的亂數分級模擬。
                        if (
                            "油" in child_name
                            or "水" in child_name
                            or "醬油" in child_name
                        ):
                            mock_qty = random.uniform(2.0, 15.0)
                        elif (
                            "香精" in child_name
                            or "色素" in child_name
                            or "精油" in child_name
                        ):
                            mock_qty = random.uniform(0.01, 0.05)
                        else:
                            mock_qty = random.uniform(0.1, 2.0)

                        BOM.objects.get_or_create(
                            parent=parent_mat,
                            child=child_mat,
                            defaults={
                                "quantity_required": Decimal(str(round(mock_qty, 4))),
                                "created_by": user,
                            },
                        )
                        boms_created += 1

                # 3. 為所有的 RAW 原料入庫 500KG，確保工單可以扣料
                today = timezone.now().date()
                raw_materials = Material.objects.filter(type="RAW")

                for id, mat in enumerate(raw_materials):
                    batch_num = f"{today.strftime('%Y%m%d')}{str(id).zfill(4)}"
                    BatchInventory.objects.get_or_create(
                        material=mat,
                        batch_number=batch_num,
                        defaults={
                            "original_qty": Decimal("700.0000"),
                            "remaining_qty": Decimal("700.0000"),
                            "received_date": today,
                            "expiration_date": today + timedelta(days=90),
                            "created_by": user,
                        },
                    )

            return Response(
                {
                    "message": "Mock Data 已經成功寫入資料庫！",
                    "stats": {
                        "total_materials_processed": materials_created,
                        "total_boms_created": boms_created,
                        "total_inventory_batches": raw_materials.count(),
                    },
                },
                status=status.HTTP_200_OK,
            )

        except Exception as e:
            return Response(
                {"error": str(e)}, status=status.HTTP_500_INTERNAL_SERVER_ERROR
            )
